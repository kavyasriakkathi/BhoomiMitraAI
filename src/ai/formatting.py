def detect_user_intents(user_message: str) -> Dict[str, bool]:
    """
    Analyze farmer user message to detect all requested domains/intents across all 13 languages.
    Reuses centralized INTENT_KEYWORDS from decision_engine.
    """
    if not user_message or not user_message.strip():
        return {
            "crop_advice": True,
            "weather": False,
            "shop": False,
            "market": False,
            "schemes": False,
            "escalation": False,
        }

    from src.ai.decision_engine import INTENT_KEYWORDS, FarmerIntent

    msg_lower = user_message.lower()

    # 1. Weather Intent (all 13 languages + legacy)
    weather_kws = INTENT_KEYWORDS.get(FarmerIntent.WEATHER, {})
    has_weather = _matches_intent_keywords(user_message, weather_kws) or any(
        p in msg_lower for p in _WEATHER_PHRASES_EN
    ) or any(p in user_message for p in _WEATHER_PHRASES_TE)

    # 2. Shop Intent (all 13 languages + legacy)
    shops_kws = INTENT_KEYWORDS.get(FarmerIntent.SHOPS, {})
    has_shop = _matches_intent_keywords(user_message, shops_kws) or any(
        p in msg_lower for p in _PURE_BUY_PHRASES
    ) or any(p in user_message for p in ["ఎక్కడ దొరుకుతుంది", "ఎక్కడ కొనాలి", "కొనాలి", "దుకాణం", "షాపు", "दुकान", "દુકાન", "দোকান", "ಅಂಗಡಿ", "കട", "ਦੁਕਾਨ", "ଦୋକାନ"])

    # 3. Market Intent (all 13 languages + legacy)
    market_kws = INTENT_KEYWORDS.get(FarmerIntent.MARKET_PRICE, {})
    has_market = _matches_intent_keywords(user_message, market_kws) or any(
        p in msg_lower for p in _MARKET_PHRASES_EN
    ) or any(p in user_message for p in _MARKET_PHRASES_TE)
    if not has_market:
        has_price_word = (
            any(w in msg_lower for w in ["price", "rate", "mandi", "bhav", "dar", "kimet"])
            or any(w in user_message for w in ["ధర", "రేటు", "మార్కెట్", "భావ", "भाव", "ದರ", "ಬೆಲೆ", "ಮಾರುಕಟ್ಟೆ", "விலை", "சந்தை", "দর", "বাজার", "ভাও", "ਕੀਮਤ", "ਮੰਡੀ", "ଭାଉ", "ମୂଲ୍ୟ", "دام", "نرخ", "ریٹ", "منڈی"])
        )
        if has_price_word and not has_shop:
            has_market = True

    # 4. Schemes Intent (all 13 languages + legacy)
    schemes_kws = INTENT_KEYWORDS.get(FarmerIntent.GOVERNMENT_SCHEMES, {})
    has_schemes = (
        _matches_intent_keywords(user_message, schemes_kws)
        or _matches_intent_keywords(user_message, _SCHEME_KEYWORDS)
        or any(p in msg_lower for p in _SCHEME_PHRASES_EN)
        or any(p in user_message for p in _SCHEME_PHRASES_TE)
    )

    # 5. Escalation Intent (all 13 languages + legacy)
    has_escalation = (
        _matches_intent_keywords(user_message, _ESCALATION_KEYWORDS)
        or any(p in msg_lower for p in _ESCALATION_PHRASES_EN)
        or any(p in user_message for p in _ESCALATION_PHRASES_TE)
    )

    # 6. Crop Advice Intent
    crop_intents = [
        FarmerIntent.CROP_HEALTH,
        FarmerIntent.IRRIGATION,
        FarmerIntent.SOWING,
        FarmerIntent.HARVESTING,
    ]
    has_direct_agri = any(
        _matches_intent_keywords(user_message, INTENT_KEYWORDS.get(ci, {})) for ci in crop_intents
    ) or any(kw in msg_lower for kw in _PURE_CROP_KEYWORDS_EN) or any(kw in user_message for kw in _PURE_CROP_KEYWORDS_TE)

    has_fert_kws = _matches_intent_keywords(user_message, INTENT_KEYWORDS.get(FarmerIntent.FERTILIZER, {}))
    has_fert_advice = any(w in msg_lower for w in _FERTILIZER_ADVICE_WORDS) or any(w in user_message for w in _FERTILIZER_ADVICE_WORDS)
    if has_fert_kws:
        if not has_shop or has_fert_advice:
            has_direct_agri = True

    is_pure_non_crop = (has_shop or has_weather or has_market or has_schemes or has_escalation) and not has_direct_agri
    has_crop_advice = has_direct_agri and not (is_pure_non_crop and not has_direct_agri)

    if not any([has_weather, has_shop, has_market, has_schemes, has_escalation]):
        has_crop_advice = True

    return {
        "crop_advice": has_crop_advice,
        "weather": has_weather,
        "shop": has_shop,
        "market": has_market,
        "schemes": has_schemes,
        "escalation": has_escalation,
    }
def clean_introductions(text: str) -> str:
    """Remove repetitive introductory greetings or preamble from text."""
    if not text:
        return ""
    cleaned = text.strip()
    changed = True
    while changed:
        changed = False
        for pattern in _COMPILED_INTROS:
            new_text = pattern.sub("", cleaned).strip()
            if new_text != cleaned:
                cleaned = new_text
                changed = True
    return cleaned.strip()


def clean_outros(text: str) -> str:
    """Remove repetitive trailing questions or closings from text."""
    if not text:
        return ""
    cleaned = text.strip()
    changed = True
    while changed:
        changed = False
        for pattern in _COMPILED_OUTROS:
            new_text = pattern.sub("", cleaned).strip()
            if new_text != cleaned:
                cleaned = new_text
                changed = True
    return cleaned.strip()


