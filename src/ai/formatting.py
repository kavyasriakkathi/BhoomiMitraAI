def get_weather_condition_desc(condition_code: int, default_desc: str, language: Optional[str] = None) -> str:
    """Map OpenWeather condition code to a localized friendly description."""
    code = normalize_language_code(language, default=FALLBACK_LANGUAGE)
    i18n = _WEATHER_CONDITIONS_I18N.get(code, _WEATHER_CONDITIONS_I18N[FALLBACK_LANGUAGE])

    if 200 <= condition_code < 300:
        return i18n["thunderstorm"]
    if 300 <= condition_code < 400:
        return i18n["drizzle"]
    if 500 <= condition_code < 600:
        return i18n["rain"]
    if 600 <= condition_code < 700:
        return i18n["snow"]
    if 700 <= condition_code < 800:
        return i18n["mist"]
    if condition_code == 800:
        return i18n["clear"]
    if 800 < condition_code < 900:
        return i18n["cloudy"]
    return default_desc


