def _matches_intent_keywords(msg: str, keywords_by_lang: Dict[str, List[str]]) -> bool:
    """Check if message matches any keywords across all languages for a given keyword mapping."""
    if not msg:
        return False
    msg_lower = msg.lower()
    for lang, kw_list in keywords_by_lang.items():
        for kw in kw_list:
            kw_clean = kw.strip().lower()
            if not kw_clean:
                continue
            if kw_clean.isascii() and kw_clean.isalnum():
                if re.search(rf"\b{re.escape(kw_clean)}\b", msg_lower):
                    return True
            else:
                if kw_clean in msg_lower or kw in msg:
                    return True
    return False


